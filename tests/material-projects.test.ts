import { expect, test } from 'bun:test';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';

test('material project partitions preserve lineage, reuse and unassigned assets without moving files', async () => {
  const repo = join(import.meta.dir, '..');
  const workspace = join(repo, 'fixtures/generated/material-projects', crypto.randomUUID());
  mkdirSync(workspace, { recursive: true });
  const code = `
    import assert from 'node:assert/strict';
    import {join} from 'node:path';
    import {writeFileSync,readFileSync,readdirSync} from 'node:fs';
    import {db} from './apps/server/src/db.ts';
    import {materialsApi} from './apps/server/src/api/materials.ts';
    const now=Date.now(), root=process.env.SFS_WORKSPACE;
    for(const id of ['p1','p2']) db.query('INSERT INTO projects(id,name,created_at) VALUES(?,?,?)').run(id,id,now);
    db.query("INSERT INTO sources(id,project_id,original_name,original_path,sha256,byte_size,probe_json,status,created_at) VALUES('source','p1','run.mp4','unchanged.mp4','hash',1,'{}','imported',?)").run(now);
    const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64');
    const original=join(root,'original.png');writeFileSync(original,png);
    const insert=(id,metadata,folder=null)=>db.query("INSERT INTO materials(id,name,raw_path,status,source,folder_id,metadata,created_at) VALUES(?,?,?,'raw','image',?,?,?)").run(id,id,original,folder,typeof metadata==='string'?metadata:JSON.stringify(metadata),now);
    insert('source-original',{source_id:'source'},'custom-folder');
    insert('source-frame',{source_id:'source',source_frame_id:'source:000000'});
    insert('legacy-image',{fromFrame:'old-frame',kept:'yes'});
    insert('shared',{});insert('unknown',{});insert('broken','{');
    insert('explicit',{project_ids:['p2','deleted','p2']});
    db.query("INSERT INTO frames(id,project_id,idx,status,metadata) VALUES('old-frame','p1',0,'ready','{}'),('reuse-one','p1',1,'ready',?),('reuse-two','p2',0,'ready',?)").run(JSON.stringify({fromMaterial:'shared'}),JSON.stringify({fromMaterial:'shared'}));
    const response=await materialsApi.handle(new Request('http://localhost/api/materials'));
    assert.equal(response.status,200);const initial=(await response.json()).materials;
    const projects=(items,id)=>items.find(m=>m.id===id).project_ids;
    assert.deepEqual(projects(initial,'source-original'),['p1']);
    assert.deepEqual(projects(initial,'source-frame'),['p1']);
    assert.deepEqual(projects(initial,'legacy-image'),['p1']);
    assert.deepEqual(projects(initial,'shared'),['p1','p2']);
    assert.deepEqual(projects(initial,'explicit'),['p2']);
    assert.deepEqual(projects(initial,'unknown'),[]);assert.deepEqual(projects(initial,'broken'),[]);
    const {backfillMaterialProjects}=await import('./apps/server/src/materialProjects.ts');
    backfillMaterialProjects(db);backfillMaterialProjects(db);
    db.query("DELETE FROM frames WHERE id IN ('old-frame','reuse-one','reuse-two')").run();
    const afterBackfill=(await (await materialsApi.handle(new Request('http://localhost/api/materials'))).json()).materials;
    assert.deepEqual(projects(afterBackfill,'legacy-image'),['p1']);assert.deepEqual(projects(afterBackfill,'shared'),['p1','p2']);
    assert.equal(afterBackfill.find(m=>m.id==='legacy-image').metadata.kept,'yes');
    const request=async(path,body)=>materialsApi.handle(new Request('http://localhost/api'+path,{method:'POST',headers:body instanceof FormData?{}:{'content-type':'application/json'},body:body instanceof FormData?body:JSON.stringify(body)}));
    const folderCount=readdirSync(join(root,'materials')).length, jobCount=db.query('SELECT COUNT(*) AS n FROM jobs').get().n;
    const invalid=new FormData();invalid.append('file',new File([png],'no.png'));invalid.append('projectId','missing');
    assert.equal((await request('/materials/upload',invalid)).status,404);
    assert.equal(readdirSync(join(root,'materials')).length,folderCount);assert.equal(db.query('SELECT COUNT(*) AS n FROM jobs').get().n,jobCount);
    const upload=new FormData();upload.append('file',new File([png],'new.png'));upload.append('projectId','p1');upload.append('metadata',JSON.stringify({custom:123}));
    const result=await request('/materials/upload',upload);assert.equal(result.status,200);const uploaded=(await result.json()).materialId;
    const list=async()=>(await (await materialsApi.handle(new Request('http://localhost/api/materials'))).json()).materials;
    assert.deepEqual(projects(await list(),uploaded),['p1']);assert.equal(db.query('SELECT COUNT(*) AS n FROM frames').get().n,0,'library upload must not insert timeline frames');
    const reused=await request('/materials/'+uploaded+'/import',{projectId:'p2'});assert.equal(reused.status,200);const reuse=await reused.json();
    assert.deepEqual(projects(await list(),uploaded),['p1','p2']);
    db.query('DELETE FROM frames WHERE id=?').run(reuse.frameIds[0]);
    assert.deepEqual(projects(await list(),uploaded),['p1','p2'],'explicit reuse association must survive deleting its copied frame');
    db.query("DELETE FROM projects WHERE id='p1'").run();
    const deleted=await list();assert.deepEqual(projects(deleted,'source-original'),[]);assert.deepEqual(projects(deleted,uploaded),['p2']);
    assert.equal(deleted.find(m=>m.id==='source-original').folder_id,'custom-folder');assert.equal(deleted.find(m=>m.id==='source-original').raw_path,original);
    assert.deepEqual(readFileSync(original),png);assert.equal(deleted.find(m=>m.id===uploaded).metadata.custom,123);
    console.log('PASS');db.close();
  `;
  const proc = Bun.spawn([process.execPath, '-e', code], { cwd: repo, env: { ...process.env, SFS_WORKSPACE: workspace }, windowsHide: true, stdout: 'pipe', stderr: 'pipe' });
  const [exit, stdout, stderr] = await Promise.all([proc.exited, new Response(proc.stdout).text(), new Response(proc.stderr).text()]);
  expect({ exit, output: stdout + stderr }).toEqual({ exit: 0, output: 'PASS\n' });
}, 30000);

test('skeletal attachment materials belong to their projects and retain membership after unbinding', async () => {
  const repo = join(import.meta.dir, '..');
  const workspace = join(repo, 'fixtures/generated/material-projects', crypto.randomUUID());
  mkdirSync(workspace, { recursive: true });
  const code = `
    import assert from 'node:assert/strict';
    import {db} from './apps/server/src/db.ts';
    import {materialsApi} from './apps/server/src/api/materials.ts';
    import {skeletalProjectsApi} from './apps/server/src/api/skeletalProjects.ts';
    import {backfillMaterialProjects} from './apps/server/src/materialProjects.ts';
    import {wsHandlers} from './apps/server/src/ws.ts';
    const now=Date.now(), events=[];wsHandlers.open({send:data=>events.push(JSON.parse(data))});
    for(const id of ['rig1','rig2'])db.query("INSERT INTO projects(id,name,kind,created_at) VALUES(?,?,'skeletal',?)").run(id,id,now);
    for(const id of ['legacy-part','new-part'])db.query("INSERT INTO materials(id,name,metadata,created_at) VALUES(?,?,?,?)").run(id,id,JSON.stringify({custom:id}),now);
    const rest={translation:[0,0,0],rotation:[0,0,0,1],scale:[1,1,1]};
    const skeleton={schemaVersion:1,kind:'skeleton',id:'test-rig',name:'Test rig',coordinateSystem:{handedness:'right',upAxis:'y',forwardAxis:'+z',unit:'pixel'},bones:[{id:'root',name:'Root',parentId:null,rest}]};
    db.query("INSERT INTO animation_assets(id,kind,name,data,created_at,updated_at) VALUES(?,'skeleton',?,?,?,?)").run(skeleton.id,skeleton.name,JSON.stringify(skeleton),now,now);
    const document=(projectId,materialId)=>({schemaVersion:1,projectId,character:materialId?{binding:{schemaVersion:1,kind:'character-binding',id:'binding',name:'Binding',skeletonId:skeleton.id,attachments:[{id:'region',name:'Region',type:'region',materialId,imageSlot:'raw',size:[32,64],pivot:[.5,1],rest}],slots:[{id:'slot',name:'Slot',boneId:'root',attachmentId:'region',drawOrder:0}]}}:null,animations:[],activeAnimationId:null});
    db.query('INSERT INTO skeletal_projects(project_id,document,updated_at) VALUES(?,?,?)').run('rig1',JSON.stringify(document('rig1','legacy-part')),now);
    const list=async()=>(await (await materialsApi.handle(new Request('http://localhost/api/materials'))).json()).materials;
    const ids=async(id)=>(await list()).find(m=>m.id===id).project_ids;
    assert.deepEqual(await ids('legacy-part'),['rig1'],'existing attachment reference must resolve without a metadata migration');
    backfillMaterialProjects(db);
    const put=async(projectId,body)=>skeletalProjectsApi.handle(new Request('http://localhost/api/projects/'+projectId+'/skeletal-document',{method:'PUT',headers:{'content-type':'application/json'},body:JSON.stringify(body)}));
    const save=await put('rig1',document('rig1','new-part'));assert.equal(save.status,200,await save.text());
    assert.deepEqual(await ids('legacy-part'),['rig1'],'backfill retains old attachment membership after replacement');
    assert.deepEqual(await ids('new-part'),['rig1']);assert.equal(events.filter(e=>e.type==='materials_changed').length,1);
    assert.equal((await put('rig2',document('rig2','new-part'))).status,200);assert.deepEqual(await ids('new-part'),['rig1','rig2']);
    assert.equal((await put('rig1',document('rig1',null))).status,200);assert.equal((await put('rig2',document('rig2',null))).status,200);
    assert.deepEqual(await ids('new-part'),['rig1','rig2'],'successful binding persists membership even after all attachments are removed');
    const before=events.length;assert.equal((await put('rig1',document('rig1','missing-material'))).status,400);assert.equal(events.length,before);
    assert.equal(JSON.parse(db.query("SELECT metadata FROM materials WHERE id='new-part'").get().metadata).custom,'new-part');
    db.query("DELETE FROM projects WHERE id='rig1'").run();assert.deepEqual(await ids('legacy-part'),[]);assert.deepEqual(await ids('new-part'),['rig2']);
    console.log('PASS');db.close();
  `;
  const proc = Bun.spawn([process.execPath, '-e', code], { cwd: repo, env: { ...process.env, SFS_WORKSPACE: workspace }, windowsHide: true, stdout: 'pipe', stderr: 'pipe' });
  const [exit, stdout, stderr] = await Promise.all([proc.exited, new Response(proc.stdout).text(), new Response(proc.stderr).text()]);
  expect({ exit, output: stdout + stderr }).toEqual({ exit: 0, output: 'PASS\n' });
}, 30000);
